const express = require('express');
const cors = require('cors');
const authRoutes = require('./routes/auth');
const menuRoutes = require('./routes/menus');
const userRoutes = require('./routes/users');
const app = express();
app.use(cors()); app.use(express.json());
app.get('/', (req, res) => res.json({ message: 'Restaurant modes API is running' }));
app.use('/api/auth', authRoutes); app.use('/api/menus', menuRoutes); app.use('/api/users', userRoutes);
app.use((req, res) => res.status(404).json({ message: 'Route not found' }));
app.use((err, req, res, next) => { console.error(err); res.status(500).json({ message: 'เกิดข้อผิดพลาดที่เซิร์ฟเวอร์' }); });
module.exports = app;
